# ------------------------------------------------------- exact equations ----
def S12(ks, kh):
    """theory/oracle-bethe.md eq. (6), D7 ordering (soft = k1, hard = k2)."""
    z12 = np.exp(1j * (ks + kh))
    return -(z12 - 2 * np.exp(1j * ks) + 1) / (z12 - 2 * np.exp(1j * kh) + 1)


def delta_phase(ks_grid, kh):
    """Continuous branch of arg S12 with delta(0)=0 (D7)."""
    ph = np.unwrap(np.angle(S12(ks_grid, kh)))
    i0 = np.argmin(np.abs(ks_grid))
    return ph - ph[i0]


def displacement(ks_grid, kh):
    """Soft packet exit displacement -d(delta)/d(k_s) (D7 sign convention,
    matching fm-displacement-scan.json)."""
    d = delta_phase(ks_grid, kh)
    return -np.gradient(d, ks_grid)


def R_pred(k, Delta, J=1.0):
    """theory/corner-b-draft.md: R = x/(1+x), x = J^4/(16 omega^2 v^2)."""
    om = J * (Delta - np.cos(k)); v = J * np.sin(k)
    x = J**4 / (16.0 * om**2 * v**2)
    return x / (1.0 + x)


