def mem_rows(prefix):
    out = []
    for r in MEM:
        if r["label"].startswith(prefix):
            res = r["result"]; p = res["params"]
            out.append(dict(Delta=float(p["Delta"]), k0=float(p["k0"]),
                            dx=float(res["dx2"]), T=float(res["transmission"]),
                            R=float(res["reflection"])))
    return out


