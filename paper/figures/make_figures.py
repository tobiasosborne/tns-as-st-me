def draw_mps(ax, x0, y0, n, r=0.024, dx=0.070, bonds=None, string=None,
             accent=BLUE):
    """A row of MPS tensors with physical legs; optional symmetry string
    (list of site indices carrying u(g)) or bond insertions (list of bond
    indices carrying V labels)."""
    xs = [x0 + i * dx for i in range(n)]
    ax.plot([xs[0] - 0.6 * dx, xs[-1] + 0.6 * dx], [y0, y0], color=INK2,
            lw=0.9, zorder=1, solid_capstyle="round")
    for i, x in enumerate(xs):
        ax.plot([x, x], [y0 + r, y0 + 2.4 * r], color=INK2, lw=0.9, zorder=1)
        ax.add_patch(Circle((x, y0), r, fc="white", ec=INK, lw=0.9, zorder=2))
    if string is not None:
        for i in string:
            x = xs[i]
            ax.add_patch(Rectangle((x - 0.55 * r, y0 + 2.4 * r), 1.1 * r, 1.5 * r,
                                   fc=accent, ec="none", zorder=3))
    if bonds is not None:
        for i, lab in bonds:
            xb = (xs[i] + xs[i + 1]) / 2
            ax.add_patch(Rectangle((xb - 0.7 * r, y0 - 0.7 * r), 1.4 * r, 1.4 * r,
                                   fc=accent, ec="none", zorder=3))
    return xs


