    fig = plt.figure(figsize=(W, 4.9 if have_prof else 3.6))
    gs = fig.add_gridspec(len(rows), 1, height_ratios=rows,
                          left=0.155, right=0.97, top=0.97, bottom=0.075,
                          hspace=0.42)
    axes = [fig.add_subplot(g) for g in gs]
    ia = 0

    # (a) space-time record of one transmission event: flipped-spin density
    if have_prof:
        with open(os.path.join(HERE, "profile-D3.0-k1.2.json")) as f:
            P = json.load(f)
        t = np.array(P["t"])
        sz = np.array(P["sz"])          # frames x sites
        dens = 0.5 - np.abs(sz)         # one-flipped-spin density (exact)
        # crossing estimator X3 computed from the saved frames (the JSON's
        # wall column is NaN due to a window-arg bug in the generator; same
        # estimator, recomputed here)
        def crossing(m, lo=60, hi=110):
            for x in range(lo, hi):
                if m[x] >= 0 > m[x + 1]:
                    return x + 1 + m[x] / (m[x] - m[x + 1])   # 1-based site
            return np.nan
        wall = np.array([crossing(m) for m in sz])
        x0, x1 = 34, 126
        cmap = LinearSegmentedColormap.from_list(
            "dens", ["#ffffff", "#cde2fb", "#5598e7", "#1c5cab", "#0d366b"])
        ax = axes[ia]; ia += 1
        im = ax.imshow(dens[:, x0:x1], origin="lower", aspect="auto",
                       extent=[x0 + 1, x1, t[0], t[-1]], cmap=cmap,
                       norm=matplotlib.colors.PowerNorm(gamma=0.42, vmin=0, vmax=0.5),
                       interpolation="nearest", rasterized=True)
        tc = P["params"]["tcollision"]
        pre = t < 0.6 * tc
        w0 = wall[pre].mean()
        ax.text(52, 12, "magnon in", color=INK, fontsize=7)
        ax.text(97, 60, "out", color=INK, fontsize=7)
        # zoom inset: the wall trajectory and its -2-site jump
        axi = ax.inset_axes([0.035, 0.52, 0.26, 0.44])
        axi.plot(np.full_like(t, w0), t, ls="--", color=MUTED, lw=0.8)
        axi.plot(wall, t, color=ORANGE, lw=1.1)
        axi.set_xlim(w0 - 3.6, w0 + 1.6); axi.set_ylim(t[0], t[-1])
        axi.set_xticks([w0 - 2, w0]); axi.set_xticklabels(["$-2$", "$0$"], fontsize=6)
        axi.set_yticks([])
        for sp in axi.spines.values():
            sp.set_linewidth(0.5); sp.set_color(INK2)
        axi.tick_params(width=0.5, length=1.8, labelsize=6)
        axi.set_title("wall position", fontsize=6, pad=1.5, color=INK)
        cb = fig.colorbar(im, ax=ax, pad=0.02, fraction=0.055, ticks=[0, 0.1, 0.3, 0.5])
